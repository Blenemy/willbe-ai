import { IBuildPromptData } from './first-email-english.prompt';

export function buildFirstEmailHebrewPrompt(data: IBuildPromptData): string {
  const { messageTemplate, company, messageEntryLeadData, targetCompanyFullInfo} = data;

  let messageTemplateString = `ברכה: ${messageTemplate.greeting}\n\n`;
  
  messageTemplateString += `מבוא (מספר מילים מקסימלי בחלק המבוא: ${messageTemplate.introduction.wordsLimit}): ${messageTemplate.introduction.text}`;
  messageTemplateString += 'המבוא צריך להיות מותאם אישית אך לא ממוקד מכירות.\n\n';

  messageTemplate.paragraphs.forEach((paragraph, index) => {
    messageTemplateString += `פסקה ${index + 1} (מספר מילים מקסימלי בפסקה ${index + 1}: ${paragraph.wordsLimit}): ${paragraph.text}\n\n`;
  });

  messageTemplateString += `פרידה (מספר מילים מקסימלי בחלק הפרידה: ${messageTemplate.goodbye.wordsLimit}): ${messageTemplate.goodbye.text}\n\n`;

  return `
    ${messageTemplate.objective}

    פורמט קריטי:
    חובה לכל פסקה להתחיל עם התגית [right] ולהסתיים עם התגית [/right]. זוהי דרישה הכרחית שחייבת להיות מיושמת בכל פסקאות האימייל ללא יוצא מן הכלל.

    מגבלת פורמט קריטית:
    עליך לייצר רק את טקסט האימייל.
    אסור לכלול:

    הערות הסבר או תגובות: (לדוגמה, "אימייל זה מותאם אישית באמצעות...", "כללתי התייחסויות ל...", "הערה: האימייל מתייחס ל...")
    ניתוח או הצדקות: (לדוגמה, "האימייל מדגיש נקודות מפתח...", "הוא מתמקד ב...", "הגישה מתמקדת ב...")
    מטא-דאטה או הערות: (לדוגמה, "סוג אימייל: ראשוני", "התאמה אישית: גבוהה", "יעד: מקבל החלטות")
    טקסט אחרי הפרידה: (לדוגמה, רשימות של תכונות כלולות, הסברים על התאמות אישיות שנעשו, ניתוח של הגישה שנעשה בה שימוש)
    כל תוכן שאינו האימייל עצמו: (לדוגמה, "הנה האימייל שנוצר:", "זהו האימייל שיצרתי:", "הנה האימייל:")
    ביטויי פתיחה: (לדוגמה, "אני מציע את האימייל הבא:", "יצרתי את האימייל הזה:", "האימייל יהיה כך:")

    האימייל חייב להסתיים בשורה האחרונה של הטקסט, ללא תוכן נוסף.
    פרמטרים לקלט:
    על החברה שלך:
    שם החברה: ${company.name}
    מגזר: ${company.sector}
    תיאור החברה: ${company.shortDescription}
    ההצעה שלך:
    שם המוצר/שירות: ${messageEntryLeadData.productService.name}
    תיאור: ${messageEntryLeadData.productService.shortDescription}
    מידע על חברת היעד:
    שם החברה: ${targetCompanyFullInfo.data.name}
    תיאור החברה: ${targetCompanyFullInfo.data.description}
    מגזרים: ${targetCompanyFullInfo.data.industry[0]}
    פוסטים אחרונים בלינקדאין מחברת היעד: ${''} (חובה להזכיר אם זמין)
    מידע על הלקוח הפוטנציאלי:
    שם: ${messageEntryLeadData.lead.leadData.name}
    תפקיד: ${messageEntryLeadData.lead.leadData.current_positions[0].role}
    תיאור תפקיד: ${''}
    סיכום מקצועי: ${messageEntryLeadData.lead.leadData.summary}
    פוסטים אחרונים בלינקדאין מהלקוח הפוטנציאלי: ${''} (חובה להזכיר אם זמין)
    מבנה ופורמט האימייל:
    אורך כולל מקסימלי: ${messageEntryLeadData.messageStructure.wordsLimit} מילים
    עליך לעקוב בדיוק אחר המבנה הזה: ${messageTemplateString}
    מבנה זה מגדיר:
    חלקים הכרחיים,
    מגבלות מילים לכל חלק,
    סדר המידע
    אימייל לדוגמה:
    השתמש באימייל זה כהשראה לטון וסגנון: ${messageTemplate.sampleMessage}
    הערה: זוהי רק דוגמה לייחוס. האימייל שלך חייב:

    לעקוב אחר המבנה והפורמט הזה: ${messageTemplateString}
    להיות מותאם אישית באופן ייחודי ללקוח הפוטנציאלי שלך
    להתייחס לתוכן שונה בהתבסס על המידע של הלקוח הפוטנציאלי שלך

    דרישות למעורבות בלינקדאין:
    אם פוסטים בלינקדאין זמינים:
    חובה להתייחס לתוכן ספציפי מהפוסטים האחרונים שלהם שהוזכרו קודם לכן במבוא:
    פוסטים אחרונים בלינקדאין מהלקוח הפוטנציאלי ופוסטים אחרונים בלינקדאין מחברת היעד. לפוסטים האחרונים בלינקדאין של הלקוח הפוטנציאלי יש עדיפות.
    השתמש בפעילות לינקדאין כדי להדגים הבנה של העדיפויות הנוכחיות שלהם
    חבר את התוכן שפורסם עם הצעת הערך
    הראה כיצד הפתרון שלך קשור לנושאים שהם דנים בהם באופן פעיל
    כללי עיצוב חשובים:
    מגבלות תוכן:

    אין התייחסויות למזג אוויר או תנאים אטמוספריים
    אין אזכור של עונות או התייחסויות עונתיות
    הימנע מביטויים כמו:

    "מקווה שיש לך יום שמשי"
    "עם בוא האביב..."
    "בימים החמים האלה..."
    "במהלך העונה הזו..."



    אין נושא לאימייל
    אין חתימה
    השתמש בפורמט <b>טקסט</b> עבור נקודות מפתח (לעולם אל תשתמש בכוכביות ** או כל פורמט אחר)
    הימנע משפה מסחרית ברורה
    פורמט שם חברה:
    האות הראשונה של כל מילה גדולה
    המר שמות באותיות גדולות לפורמט כותרת
    דוגמאות:
    "RIVER ISLAND" צריך להיכתב כ-"River Island"
    "GUESS" צריך להיכתב כ-"Guess"
    "BANCO SANTANDER" צריך להיכתב כ-"Banco Santander"
    זה חל על כל האזכורים של ${targetCompanyFullInfo.data.name} באימייל
    דרישות תגית מודגשת - חובה:
    עליך להשתמש בתגיות <b> ו-</b> (לעולם לא בכוכביות **) כדי להדגיש רק את המשפטים בעלי ההשפעה והרלוונטיות הגבוהה ביותר בכל פסקה. המטרה היא להדגיש רק את הנקודות המרכזיות, לא את כל התוכן. כל פסקה חייבת להכיל לכל היותר משפט מודגש אחד המייצג את הנקודה החשובה ביותר.
    הנחיות הדגשה לכל פסקה:
    פסקת פתיחה/מבוא:
    הדגש רק את ההערה הרלוונטית ביותר על הלקוח הפוטנציאלי
    נכון: "עקבתי אחר עבודתך ו<b>היישום האחרון שלך של פתרונות בני-קיימא הפחית את ההשפעה הסביבתית ב-40%</b>"
    לא נכון: "<b>עקבתי אחר עבודתך והיישום האחרון שלך של פתרונות בני-קיימא הפחית את ההשפעה הסביבתית ב-40%</b>"
    פסקת הצעת ערך:
    הדגש רק את היתרון העיקרי או את המאפיין המבחין העיקרי
    נכון: "הפלטפורמה שלנו מציעה פונקציונליות מרובה, ו<b>עזרנו לחברות דומות להפחית את עלויות התפעול שלהן ב-30%</b>"
    לא נכון: "<b>הפלטפורמה שלנו מציעה פונקציונליות מרובה, ועזרנו לחברות דומות להפחית את עלויות התפעול שלהן ב-30%</b>"
    פסקת הוכחה חברתית:
    הדגש רק את ההישג או התוצאה בעלי ההשפעה הגבוהה ביותר
    נכון: "אנו משתפים פעולה עם לקוחות שונים בתעשייה ו<b>עזרנו ל-River Island להגדיל את היעילות שלהם ב-45%</b>"
    לא נכון: "<b>אנו משתפים פעולה עם לקוחות שונים בתעשייה ועזרנו ל-River Island להגדיל את היעילות שלהם ב-45%</b>"
    פסקת קריאה לפעולה:
    הדגש רק את הצעת הפגישה הקונקרטית
    נכון: "<b>האם תהיה פנוי לקפה וירטואלי של 30 דקות ביום חמישי הבא בשעה 11:00?</b>"
    לא נכון: "<b>הייתי שמח על הזדמנות להיפגש. האם תהיה פנוי לקפה וירטואלי של 30 דקות ביום חמישי הבא בשעה 11:00?</b>"
    כללי הדגשה כלליים:
    מקסימום משפט מודגש אחד לכל פסקה
    הדגש רק את הנקודה החשובה או בעלת ההשפעה ביותר
    הימנע מהדגשת מידע הקשרי או מחברים
    משפטים מודגשים חייבים להיות קריאים באופן עצמאי ולשמור על משמעות מלאה
    טקסט מודגש לא צריך לעלות על 25% מסך תוכן האימייל
    דוגמאות לאיזון נכון:
    טוב (הדגשה סלקטיבית):
    "היי ג'ון,
    עקבתי אחר המסע שלך ו<b>ההתרחבות הבינלאומית האחרונה שלך יצרה תוצאות יוצאות דופן</b>.
    מהייעוץ המתמחה שלנו, <b>עזרנו לחברות דומות להפחית את עלויות ההתרחבות שלהן ב-40%</b>.
    אנו עובדים עם לקוחות מרובים במגזר ו<b>לאחרונה עזרנו לחברה X להשלים את ההתרחבות שלהם ב-50% מהר יותר</b>.
    <b>האם תהיה פנוי לפגישה ביום חמישי בשעה 11:00 כדי לשתף את הניסיון שלנו?</b>
    כל טוב,"
    רע (יותר מדי הדגשה):
    "<b>היי ג'ון,
    עקבתי אחר המסע שלך וההתרחבות הבינלאומית האחרונה שלך יצרה תוצאות יוצאות דופן.
    מהייעוץ המתמחה שלנו, עזרנו לחברות דומות להפחית את עלויות ההתרחבות שלהן ב-40%.
    אנו עובדים עם לקוחות מרובים במגזר ולאחרונה עזרנו לחברה X להשלים את ההתרחבות שלהם ב-50% מהר יותר.
    האם תהיה פנוי לפגישה ביום חמישי בשעה 11:00 כדי לשתף את הניסיון שלנו?</b>
    כל טוב,"
    דרישות התאמה אישית:
    חייב להתייחס לפחות לפרט ספציפי אחד מתוך:
    הפוסטים שלהם בלינקדאין (אם זמינים)
    תיאור החברה
    תפקיד ואחריות
    הקשר תעשייתי
    הצג מחקר והבנה ברורים של העסק שלהם
    חבר את האתגרים שלהם עם הפתרון שלך מבלי להיות פרסומי
    התשובה שלך צריכה להכיל רק את טקסט האימייל, תוך מעקב אחר המבנה המסופק תוך שימוש באימייל לדוגמה כהתייחסות לטון וסגנון. צור הודעה מותאמת אישית מאוד שמדגימה שסקרת ביסודיות את הפרופיל שלהם ומבין את ההקשר שלהם.
    דרישות שפה:
    הנחיה זו חייבת לייצר תשובות בעברית תקנית ישראלית באופן עקבי לאורך כל האימייל. יש לשמור על עקביות בכתיב, מונחים וביטויים לאורך כל התגובה.
    דוגמאות לעקביות בעברית ישראלית:

    מונחים טכניים: "התאמה אישית", "ניתוח", "ארגון"
    מונחים מקצועיים: "תוכנית", "קטלוג"
    זמנים: "11:00" או "11:00 בבוקר"
    תאריכים: "15 בספטמבר 2024" או "ט"ו באלול תשפ"ד"
    פנייה: "שלום רב", "בוקר טוב", "ערב טוב"
    סיומות: "בברכה", "כל טוב", "בכבוד רב"

    יש לשמור על העקביות בעברית תקנית לאורך כל חלקי האימייל, כולל ברכות, טקסט גוף, וסיומים, תוך התחשבות בכללי הדקדוק והתחביר העבריים.
  `;
}